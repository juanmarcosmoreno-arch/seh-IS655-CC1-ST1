#!/usr/bin/env python3
"""Map ancestry-informative breakpoint intervals around the ST2187 seh locus."""

from __future__ import annotations

import csv, datetime as dt, os, re, subprocess
from pathlib import Path
from Bio import SeqIO
from Bio.Seq import Seq

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"results/seh_st1_bovine/st2187_breakpoints"
MAFFT=ROOT/".micromamba/envs/gridion_pangenome_pip/bin/mafft"
SAMPLES={
 "cepa18":(ROOT/"results/bakta/cepa_18_barcode02/cepa_18_barcode02.fna",ROOT/"results/bakta/cepa_18_barcode02/cepa_18_barcode02.gff3","recipient"),
 "23EV612":(ROOT/"results/voss_2025_msphere_st1/bakta/23EV612/23EV612.fna",ROOT/"results/voss_2025_msphere_st1/bakta/23EV612/23EV612.gff3","ST1_like"),
 "GCA_031889545.1":(ROOT/"results/public_context_regional/bakta/GCA_031889545.1/GCA_031889545.1.fna",ROOT/"results/public_context_regional/bakta/GCA_031889545.1/GCA_031889545.1.gff3","ST2187_negative"),
}
FLANK=15000

def anchors(gff):
 d={}; features=[]
 for line in open(gff):
  if line.startswith("#"): continue
  x=line.rstrip().split("\t")
  if len(x)!=9: continue
  a=dict(p.split("=",1) for p in x[8].split(";") if "=" in p); gene=a.get("gene","")
  r={"contig":x[0],"type":x[2],"start":int(x[3]),"end":int(x[4]),"strand":x[6],"gene":gene,"name":a.get("Name",a.get("product",""))}
  features.append(r)
  if x[2]=="CDS" and gene in {"rlmH","cstA"}: d[gene]=r
 return d,features

def genome(path): return {r.id:str(r.seq).upper() for r in SeqIO.parse(path,"fasta")}

def main():
 OUT.mkdir(parents=True,exist_ok=True); windows={}; maps={}; all_features={}
 for name,(fa,gff,role) in SAMPLES.items():
  a,features=anchors(gff); all_features[name]=features; assert a["rlmH"]["contig"]==a["cstA"]["contig"]
  contig=a["rlmH"]["contig"]; seq=genome(fa)[contig]; lo=max(1,min(a["rlmH"]["start"],a["cstA"]["start"])-FLANK); hi=min(len(seq),max(a["rlmH"]["end"],a["cstA"]["end"])+FLANK)
  raw=seq[lo-1:hi]; forward=a["rlmH"]["start"]<a["cstA"]["start"]
  norm=raw if forward else str(Seq(raw).reverse_complement())
  windows[name]=norm; maps[name]={"contig":contig,"lo":lo,"hi":hi,"forward":forward,"role":role}
 with (OUT/"cepa18_wide_window.fasta").open("w") as h: h.write(f">cepa18|{maps['cepa18']}\n{windows['cepa18']}\n")
 combined=OUT/"three_wide_windows.fasta"
 with combined.open("w") as h:
  for n,s in windows.items(): h.write(f">{n}\n{s}\n")
 env=os.environ.copy(); env["MAFFT_BINARIES"]=str(MAFFT.parent.parent/"libexec/mafft")
 run=subprocess.run([str(MAFFT),"--auto",str(combined)],text=True,capture_output=True,check=True,env=env)
 (OUT/"three_way_alignment.fasta").write_text(run.stdout)
 aln={r.id:str(r.seq).upper() for r in SeqIO.parse(OUT/"three_way_alignment.fasta","fasta")}
 # Provide an XMFA-compatible single collinear block; generated by MAFFT because progressiveMauve was unavailable.
 with (OUT/"three_way_mauve_alignment.xmfa").open("w") as h:
  h.write("#FormatVersion Mauve1\n#Generated by MAFFT as one collinear block; not progressiveMauve\n")
  for i,n in enumerate(("cepa18","23EV612","GCA_031889545.1"),1): h.write(f"> {i}:1-{len(windows[n])} + {n}\n{aln[n]}\n")
  h.write("=\n")
 # Map alignment columns to recipient coordinates and classify donor-informative sites.
 pos=0; informative=[]; column_rows=[]
 for col,(r,s,n) in enumerate(zip(aln["cepa18"],aln["23EV612"],aln["GCA_031889545.1"]),1):
  if r!="-": pos+=1
  if r in "ACGT" and s in "ACGT" and n in "ACGT" and s!=n:
   state="ST1_like" if r==s else ("ST2187_like" if r==n else "other")
   informative.append((pos,state,col)); column_rows.append({"cepa18_window_pos":pos,"alignment_column":col,"cepa18_base":r,"st1_base":s,"st2187_negative_base":n,"ancestry_state":state})
 # Central ST1-like run: markers between the last ST2187-like marker before the locus and first after it.
 a18,_=anchors(SAMPLES["cepa18"][1]); m=maps["cepa18"]
 def to_window(coord): return coord-m["lo"]+1 if m["forward"] else m["hi"]-coord+1
 locus_lo=min(to_window(a18["rlmH"]["start"]),to_window(a18["rlmH"]["end"]),to_window(a18["cstA"]["start"]),to_window(a18["cstA"]["end"])); locus_hi=max(to_window(a18["rlmH"]["start"]),to_window(a18["rlmH"]["end"]),to_window(a18["cstA"]["start"]),to_window(a18["cstA"]["end"]))
 left_neg=max((p for p,state,_ in informative if state=="ST2187_like" and p<locus_lo),default=1); right_neg=min((p for p,state,_ in informative if state=="ST2187_like" and p>locus_hi),default=len(windows["cepa18"]))
 first_st1=min((p for p,state,_ in informative if state=="ST1_like" and left_neg<p<right_neg),default=locus_lo); last_st1=max((p for p,state,_ in informative if state=="ST1_like" and left_neg<p<right_neg),default=locus_hi)
 # Sliding identity in alignment space, using 100 recipient bases every 10 bases.
 sliding=[]
 col_by_pos={}; p=0
 for c,b in enumerate(aln["cepa18"]):
  if b!="-": p+=1; col_by_pos[p]=c
 for start in range(1,len(windows["cepa18"])-99,10):
  cs=col_by_pos[start]; ce=col_by_pos[start+99]; r=aln["cepa18"][cs:ce+1]; s=aln["23EV612"][cs:ce+1]; n=aln["GCA_031889545.1"][cs:ce+1]
  def ident(x):
   comp=[(a,b) for a,b in zip(r,x) if a in "ACGT" and b in "ACGT"]
   return (100*sum(a==b for a,b in comp)/len(comp),len(comp)) if comp else (0,0)
  si,sc=ident(s); ni,nc=ident(n); sliding.append({"cepa18_window_start":start,"cepa18_window_end":start+99,"identity_vs_ST1_pct":f"{si:.3f}","comparable_vs_ST1_bp":sc,"identity_vs_ST2187_negative_pct":f"{ni:.3f}","comparable_vs_ST2187_negative_bp":nc,"identity_difference_ST1_minus_ST2187":f"{si-ni:.3f}"})
 def abs_interval(x,y):
  return (m["lo"]+x-1,m["lo"]+y-1) if m["forward"] else (m["hi"]-y+1,m["hi"]-x+1)
 ul,ur=abs_interval(left_neg+1,first_st1); dl,dr=abs_interval(last_st1,right_neg-1)
 def feature_at(lo,hi):
  z=[f for f in all_features["cepa18"] if f["type"]!="region" and f["contig"]==m["contig"] and f["start"]<=hi and f["end"]>=lo]
  return "|".join(f["gene"] or f["name"] or f["type"] for f in z) or "intergenic"
 breakpoints=[{"breakpoint":"upstream","recipient_window_interval":f"{left_neg+1}-{first_st1}","cepa18_genome_interval":f"{min(ul,ur)}-{max(ul,ur)}","uncertainty_bp":first_st1-left_neg,"overlapping_feature":feature_at(min(ul,ur),max(ul,ur))},{"breakpoint":"downstream","recipient_window_interval":f"{last_st1}-{right_neg-1}","cepa18_genome_interval":f"{min(dl,dr)}-{max(dl,dr)}","uncertainty_bp":right_neg-last_st1,"overlapping_feature":feature_at(min(dl,dr),max(dl,dr))}]
 def wt(path,rows):
  with path.open("w",newline="") as h: w=csv.DictWriter(h,fieldnames=list(rows[0]),delimiter="\t");w.writeheader();w.writerows(rows)
 wt(OUT/"sliding_window_identity.tsv",sliding); wt(OUT/"ancestry_informative_sites.tsv",column_rows); wt(OUT/"st2187_breakpoint_coordinates.tsv",breakpoints)
 mh=[{"breakpoint":b["breakpoint"],"homology_interval_bp":b["uncertainty_bp"],"interpretation":"breakpoint unresolved within shared homologous interval; no unique nucleotide cut site can be assigned","TSD_detected":"not_supported"} for b in breakpoints]; wt(OUT/"breakpoint_microhomology.tsv",mh)
 summary=[{"metric":"left_flanking_ST2187_marker_window_pos","value":left_neg},{"metric":"first_central_ST1_marker_window_pos","value":first_st1},{"metric":"last_central_ST1_marker_window_pos","value":last_st1},{"metric":"right_flanking_ST2187_marker_window_pos","value":right_neg},{"metric":"minimum_ST1_like_tract_bp","value":last_st1-first_st1+1},{"metric":"maximum_ST1_like_tract_bp","value":right_neg-left_neg-1},{"metric":"informative_sites_total","value":len(informative)}]; wt(OUT/"breakpoint_summary.tsv",summary)
 (OUT/"analysis.log").write_text("\n".join([f"run_date={dt.date.today().isoformat()}","script=scripts/124_map_st2187_recombination_breakpoints.py",f"mafft={run.stderr.splitlines()[0] if run.stderr else '7.526'}","alignment=three normalized 15-kb-flanked windows; MAFFT --auto","negative_comparator=GCA_031889545.1","breakpoint_definition=interval between nearest discordant ancestry-informative markers","sliding_window=100 bp; step=10 bp","progressiveMauve=unavailable; XMFA contains the MAFFT collinear alignment and is labelled accordingly"]) + "\n")

if __name__=="__main__": main()
